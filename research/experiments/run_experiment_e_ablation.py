"""
Experiment E: Comprehensive Ablation Study

Evaluates 5 system variants on the full held-out test suite (8,977 in-domain + 100 OOD)
to disentangle the exact marginal contributions of each component:
  Variant 1: Confidence-only policy
  Variant 2: Confidence + Intent-Risk policy
  Variant 3: Confidence + Intent Risk + Sentiment Analysis
  Variant 4: Confidence + Intent Risk + OOD Detection
  Variant 5: Full System (Confidence + Intent Risk + Sentiment + OOD Detection)
"""

import os
import sys
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "../..")))

from research.experiments.common import (
    load_dataset_and_split,
    load_vectorizer_and_models,
    save_csv_dual,
    get_ood_benchmark_queries,
    RESEARCH_RESULTS_DIR,
    RESEARCH_GRAPHS_DIR,
    EVAL_DIR
)
from src.intent_risk_map import get_intent_risk_level, INTENT_RISK_MAP
from src.sentiment_analyzer import SentimentAnalyzer
from src.ood_detector import OODDetector
from src.risk_engine import RiskEngine
from src.decision_engine import DecisionEngine


def run_experiment_e():
    print("=" * 75)
    print("EXPERIMENT E: COMPREHENSIVE ABLATION STUDY")
    print("=" * 75)

    # 1. Load data and models
    X_train, X_test, y_train, y_test, _ = load_dataset_and_split()
    vectorizer, models = load_vectorizer_and_models()
    calibrated_model = models["Calibrated Linear SVM"]

    # 2. Check if trace already generated by Experiment D
    trace_path = os.path.join(RESEARCH_RESULTS_DIR, "research_baseline_evaluation_trace.csv")
    if os.path.exists(trace_path):
        print(f"Loading pre-computed test suite evaluation trace from: {trace_path}")
        trace_df = pd.read_csv(trace_path)
        trace_df["pred_intent_risk"] = trace_df["pred_intent"].apply(get_intent_risk_level)
        trace_df["sentiment"] = trace_df["sentiment_pred"]
        trace_df["decision_full"] = trace_df["p4_decision"]
    else:
        # Build Reference Matrix
        print("Transforming training data for OOD reference matrix...")
        ref_matrix = vectorizer.transform(X_train)

        sentiment_analyzer = SentimentAnalyzer()
        ood_detector = OODDetector(vectorizer=vectorizer, reference_matrix=ref_matrix)
        risk_engine = RiskEngine()
        decision_engine = DecisionEngine(confidence_threshold=0.85)

        ood_queries = get_ood_benchmark_queries()
        in_domain_records = []
        for query, true_intent in zip(X_test, y_test):
            is_hr = (INTENT_RISK_MAP.get(true_intent, "LOW") == "HIGH")
            in_domain_records.append({
                "query": query,
                "true_intent": true_intent,
                "is_ood": False,
                "is_high_risk": is_hr
            })

        ood_records = []
        for query in ood_queries:
            ood_records.append({
                "query": query,
                "true_intent": "OUT_OF_DOMAIN",
                "is_ood": True,
                "is_high_risk": False
            })

        test_pool = pd.DataFrame(in_domain_records + ood_records)
        total_samples = len(test_pool)
        print(f"Total Test Pool: {total_samples}")

        X_vec = vectorizer.transform(test_pool["query"])
        pred_intents = calibrated_model.predict(X_vec)
        prob_matrix = calibrated_model.predict_proba(X_vec)
        conf_scores = prob_matrix.max(axis=1)

        traces = []
        for i in range(total_samples):
            query = test_pool.iloc[i]["query"]
            pred_intent = pred_intents[i]
            conf = float(conf_scores[i])
            query_vec = X_vec[i]

            sent_data = sentiment_analyzer.analyze(query)
            ood_data = ood_detector.detect(query, conf, query_vector=query_vec)
            risk_data = risk_engine.evaluate_risk(pred_intent, conf, sent_data, ood_data)
            full_dec = decision_engine.make_decision(query, pred_intent, conf, sent_data, ood_data, risk_data)

            traces.append({
                "query": query,
                "true_intent": test_pool.iloc[i]["true_intent"],
                "pred_intent": pred_intent,
                "confidence": conf,
                "is_ood_true": test_pool.iloc[i]["is_ood"],
                "is_high_risk_true": test_pool.iloc[i]["is_high_risk"],
                "pred_intent_risk": get_intent_risk_level(pred_intent),
                "sentiment": sent_data["sentiment"],
                "is_ood_pred": ood_data["is_ood"],
                "decision_full": full_dec["decision"]
            })
        trace_df = pd.DataFrame(traces)

    # 6. Evaluate Each Ablation Variant
    variants = [
        ("Variant 1: Confidence Only", "v1"),
        ("Variant 2: Confidence + Intent Risk", "v2"),
        ("Variant 3: Confidence + Intent Risk + Sentiment", "v3"),
        ("Variant 4: Confidence + Intent Risk + OOD", "v4"),
        ("Variant 5: Full System (Conf + Risk + Sent + OOD)", "v5")
    ]

    ablation_rows = []
    num_total = len(trace_df)
    num_hr = trace_df["is_high_risk_true"].sum()
    num_ood = trace_df["is_ood_true"].sum()

    for var_title, var_key in variants:
        decisions = []
        for _, row in trace_df.iterrows():
            conf = row["confidence"]
            pred_risk = row["pred_intent_risk"]
            sent = row["sentiment"]
            is_ood_pred = row["is_ood_pred"]

            if var_key == "v1":
                # Only confidence threshold
                dec = "AUTOMATE" if conf >= 0.85 else "HUMAN_ESCALATION"

            elif var_key == "v2":
                # Confidence + Intent Risk
                if pred_risk == "HIGH":
                    dec = "HUMAN_ESCALATION"
                elif conf >= 0.85:
                    dec = "AUTOMATE"
                elif conf >= 0.55:
                    dec = "CLARIFY"
                else:
                    dec = "HUMAN_ESCALATION"

            elif var_key == "v3":
                # Confidence + Intent Risk + Sentiment (negative sentiment boosts escalation)
                if pred_risk == "HIGH" or (sent == "NEGATIVE" and pred_risk == "MEDIUM" and conf < 0.90):
                    dec = "HUMAN_ESCALATION"
                elif conf >= 0.85:
                    dec = "AUTOMATE"
                elif conf >= 0.55:
                    dec = "CLARIFY"
                else:
                    dec = "HUMAN_ESCALATION"

            elif var_key == "v4":
                # Confidence + Intent Risk + OOD
                if is_ood_pred or pred_risk == "HIGH":
                    dec = "HUMAN_ESCALATION"
                elif conf >= 0.85:
                    dec = "AUTOMATE"
                elif conf >= 0.55:
                    dec = "CLARIFY"
                else:
                    dec = "HUMAN_ESCALATION"

            elif var_key == "v5":
                # Full System
                dec = row["decision_full"]

            decisions.append(dec)

        dec_series = pd.Series(decisions)
        num_auto = (dec_series == "AUTOMATE").sum()
        num_esc = (dec_series == "HUMAN_ESCALATION").sum()
        num_clar = (dec_series == "CLARIFY").sum()

        cov = num_auto / num_total
        esc_rate = num_esc / num_total
        clar_rate = num_clar / num_total

        auto_mask = (dec_series == "AUTOMATE")
        if num_auto > 0:
            correct_auto = ((trace_df["pred_intent"] == trace_df["true_intent"]) & 
                            (~trace_df["is_ood_true"]) & 
                            auto_mask).sum()
            sel_acc = correct_auto / num_auto
            inc_auto_rate = 1.0 - sel_acc
        else:
            sel_acc = np.nan
            inc_auto_rate = np.nan

        hr_auto_count = (auto_mask & trace_df["is_high_risk_true"]).sum()
        hr_auto_rate = hr_auto_count / num_hr if num_hr > 0 else 0.0

        ood_auto_count = (auto_mask & trace_df["is_ood_true"]).sum()
        ood_fa_rate = ood_auto_count / num_ood if num_ood > 0 else 0.0

        ablation_rows.append({
            "Variant": var_title,
            "Total Queries": num_total,
            "Automated Count": num_auto,
            "Escalated Count": num_esc,
            "Clarified Count": num_clar,
            "Coverage (%)": round(cov * 100, 2),
            "Selective Accuracy (%)": round(sel_acc * 100, 2),
            "Incorrect Automation Rate (%)": round(inc_auto_rate * 100, 2),
            "Human Escalation Rate (%)": round(esc_rate * 100, 2),
            "Clarification Rate (%)": round(clar_rate * 100, 2),
            "High-Risk Automation Rate (%)": round(hr_auto_rate * 100, 2),
            "High-Risk Automated Count": hr_auto_count,
            "OOD False-Acceptance Rate (%)": round(ood_fa_rate * 100, 2),
            "OOD False-Accepted Count": ood_auto_count
        })

    abl_df = pd.DataFrame(ablation_rows)

    print("\n" + "=" * 75)
    print("ABLATION STUDY RESULTS (FULL TEST SUITE)")
    print("=" * 75)
    print(abl_df.to_string(index=False))

    save_csv_dual(abl_df, "research_ablation_results.csv")

    # 7. Generate Ablation Figure
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 6))

    labels = ["V1: Conf Only", "V2: +Risk", "V3: +Risk+Sent", "V4: +Risk+OOD", "V5: Full System"]
    x = np.arange(len(labels))
    w = 0.35

    # Subplot 1: Automation Coverage vs. Selective Accuracy
    ax1.plot(x, abl_df["Coverage (%)"], marker='o', linewidth=2.5, markersize=8, color="#2563EB", label="Coverage (%)")
    ax1.plot(x, abl_df["Selective Accuracy (%)"], marker='s', linewidth=2.5, markersize=8, color="#10B981", label="Selective Accuracy (%)")
    ax1.set_ylabel("Percentage (%)", fontsize=12, fontweight="bold")
    ax1.set_title("Coverage vs. Selective Accuracy Across Ablations", fontsize=13, fontweight="bold", pad=12)
    ax1.set_xticks(x)
    ax1.set_xticklabels(labels, fontsize=10, rotation=15)
    ax1.set_ylim(60, 105)
    ax1.legend(loc="lower left", frameon=True)
    ax1.grid(True, linestyle="--", alpha=0.5)

    for i in range(len(x)):
        ax1.annotate(f"{abl_df['Coverage (%)'].iloc[i]}%", (x[i], abl_df["Coverage (%)"].iloc[i] + 1.2), ha='center', fontsize=9, fontweight='bold', color="#2563EB")
        ax1.annotate(f"{abl_df['Selective Accuracy (%)'].iloc[i]}%", (x[i], abl_df["Selective Accuracy (%)"].iloc[i] - 2.5), ha='center', fontsize=9, fontweight='bold', color="#10B981")

    # Subplot 2: Safety Violations Drop
    ax2.bar(x - w/2, abl_df["High-Risk Automation Rate (%)"], w, label="High-Risk Automation Rate (%)", color="#EF4444", alpha=0.85)
    ax2.bar(x + w/2, abl_df["OOD False-Acceptance Rate (%)"], w, label="OOD False-Acceptance Rate (%)", color="#F59E0B", alpha=0.85)
    ax2.set_ylabel("Violation Rate (%)", fontsize=12, fontweight="bold")
    ax2.set_title("Safety Violations Elimination Across Variants", fontsize=13, fontweight="bold", pad=12)
    ax2.set_xticks(x)
    ax2.set_xticklabels(labels, fontsize=10, rotation=15)
    ax2.set_ylim(0, 105)
    ax2.legend(loc="upper right", frameon=True)
    ax2.grid(True, linestyle="--", alpha=0.5)

    for i in range(len(x)):
        ax2.text(x[i] - w/2, abl_df["High-Risk Automation Rate (%)"].iloc[i] + 1.5, f"{abl_df['High-Risk Automation Rate (%)'].iloc[i]}%", ha='center', fontsize=8, fontweight='bold')
        ax2.text(x[i] + w/2, abl_df["OOD False-Acceptance Rate (%)"].iloc[i] + 1.5, f"{abl_df['OOD False-Acceptance Rate (%)'].iloc[i]}%", ha='center', fontsize=8, fontweight='bold')

    plt.tight_layout()

    plot_path1 = os.path.join(RESEARCH_GRAPHS_DIR, "research_ablation_plot.png")
    plot_path2 = os.path.join(EVAL_DIR, "research_ablation_plot.png")
    plt.savefig(plot_path1, dpi=300, bbox_inches="tight")
    plt.savefig(plot_path2, dpi=300, bbox_inches="tight")
    plt.close()

    print(f"\n[Figure] Ablation graph saved: {plot_path1}")
    print(f"[Figure] Ablation graph saved: {plot_path2}")


if __name__ == "__main__":
    run_experiment_e()
